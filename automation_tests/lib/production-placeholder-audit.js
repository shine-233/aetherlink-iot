const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const repositoryInventory = require('../scripts/generate_repository_inventory');

const DEFAULT_ALLOWLIST = path.join(
  repositoryInventory.projectRoot,
  'automation_tests',
  'coverage-contract',
  'production-placeholder-allowlist.json'
);
const SOURCE_EXTENSIONS = new Set(['.go', '.js', '.mjs', '.cjs', '.ts', '.tsx', '.vue']);
const SKIPPED_CATEGORIES = new Set([
  'test',
  'documentation',
  'generated-output',
  'third-party',
  'lockfile',
  'binary-asset'
]);
const DEFAULT_ROOTS = Object.freeze([
  'frontend/src/main.ts',
  'frontend/src/router/index.ts',
  'frontend/src/router/routes/index.ts',
  'frontend/src/router/elegant/imports.ts',
  'frontend/src/router/elegant/routes.ts',
  'frontend/src/router/elegant/automationRoutes.ts',
  'frontend/src/router/elegant/deviceRoutes.ts',
  'frontend/src/router/elegant/systemRoutes.ts',
  'frontend/src/router/elegant/visualizationRoutes.ts',
  'backend/main.go',
  'mqtt-broker/cmd/gmqttd/main.go'
]);
const MUTATION_NAME = /^(?:Apply|Cancel|Connect|Create|Delete|Deliver|Execute|Publish|Register|Run|Save|Send|Set|Start|Stop|Sync|Trigger|Update|Upload|Write)/;
const TERMINAL_BOOLEAN_KEY = /["'`]?(?:delivered|synced|published|triggered)["'`]?\s*:\s*true\b/i;
const TERMINAL_STATE_KEY = /["'`]?(?:status|state|result)["'`]?\s*:\s*["'`](?:delivered|synced|published|triggered)["'`]/i;
const SUCCESS_CONSTRUCTOR = /(?:return\b|JSON\s*\.|(?:map|object|response|result)\s*[:=])/i;
const PLACEHOLDER_TEXT = /\b(?:not[ -]?implemented|unimplemented|stub(?:bed)?)\b|待实现|未实现|占位实现/i;
const DEFAULT_RULES = Object.freeze([
  'explicit-placeholder',
  'empty-success-mutation',
  'fabricated-terminal-success',
  'discarded-side-effect-error'
]);
const GENERATED_FAMILIES = Object.freeze([
  /^(?:backend\/internal\/(?:model|query)\/.*\.gen\.go)$/,
  /^backend\/docs\/(?:docs\.go|swagger\.(?:json|yaml))$/,
  /^backend\/third_party\/grpc\/.*\.pb\.go$/,
  /^mqtt-broker\/.*(?:\.pb\.go|mock[^/]*\.go)$/,
  /^frontend\/src\/router\/elegant\/(?:imports|routes)\.ts$/
]);
const GENERATED_MARKER = /(?:code generated .* do not edit|generated by (?:elegant-router|mockgen|protoc|gorm)|@generated)/i;

function normalizeRelativePath(value) {
  const normalized = String(value || '').replaceAll('\\', '/').replace(/^\.\//, '');
  if (!normalized || path.posix.isAbsolute(normalized) || normalized.split('/').includes('..')) return null;
  return normalized;
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function resolveSourceCandidate(specifier, fromFile, catalog) {
  let relative;
  if (specifier.startsWith('@/')) relative = `frontend/src/${specifier.slice(2)}`;
  else if (specifier.startsWith('~/')) relative = `frontend/${specifier.slice(2)}`;
  else if (specifier.startsWith('.')) {
    relative = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), specifier));
  } else {
    return null;
  }
  const candidates = [
    relative,
    ...['.ts', '.tsx', '.vue', '.js', '.mjs', '.cjs', '.go'].map(extension => `${relative}${extension}`),
    ...['index.ts', 'index.tsx', 'index.vue', 'index.js'].map(file => `${relative}/${file}`)
  ];
  return candidates.find(candidate => catalog.has(candidate)) || null;
}

function frontendDependencies(source) {
  const values = [];
  const pattern = /(?:import|export)\s+(?:[^'";]+?\s+from\s+)?['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;
  for (const match of source.matchAll(pattern)) values.push(match[1] || match[2]);
  return values.filter(Boolean);
}

function backendDependencies(source, fromFile, catalog) {
  const dependencies = [];
  const modulePrefix = 'aetherlink-iot/backend/';
  for (const match of source.matchAll(/"(aetherlink-iot\/backend\/[^"\s]+)"/g)) {
    const importPath = match[1];
    const directory = `backend/${importPath.slice(modulePrefix.length)}`;
    for (const candidate of catalog) {
      if (candidate.startsWith(`${directory}/`) && path.posix.extname(candidate) === '.go') dependencies.push(candidate);
    }
  }
  if (fromFile.startsWith('mqtt-broker/')) {
    for (const match of source.matchAll(/"(github\.com\/DrmagicE\/gmqtt\/[^"\s]+)"/g)) {
      const directory = `mqtt-broker/${match[1].slice('github.com/DrmagicE/gmqtt/'.length)}`;
      for (const candidate of catalog) {
        if (candidate.startsWith(`${directory}/`) && path.posix.extname(candidate) === '.go') dependencies.push(candidate);
      }
    }
  }
  return dependencies;
}

function collectFrontendReachableFiles(catalog, options = {}) {
  return collectReachableFiles(catalog, options.frontendRoots || DEFAULT_ROOTS.filter(item => item.startsWith('frontend/')), 'frontend', options);
}

function collectBackendReachableFiles(catalog, options = {}) {
  const roots = options.backendRoots || DEFAULT_ROOTS.filter(item => !item.startsWith('frontend/'));
  return collectReachableFiles(catalog, roots, 'backend', options);
}

function collectReachableFiles(catalog, roots, kind, options) {
  const projectRoot = options.projectRoot || repositoryInventory.projectRoot;
  const readFile = options.readFile || (relative => fs.readFileSync(path.join(projectRoot, relative), 'utf8'));
  const reachable = new Set();
  const queue = roots.filter(item => catalog.has(item));
  while (queue.length) {
    const current = queue.shift();
    if (reachable.has(current)) continue;
    reachable.add(current);
    let source;
    try {
      source = readFile(current);
    } catch {
      continue;
    }
    const dependencies = kind === 'frontend'
      ? frontendDependencies(source).map(value => resolveSourceCandidate(value, current, catalog)).filter(Boolean)
      : backendDependencies(source, current, catalog);
    for (const dependency of dependencies) {
      if (!reachable.has(dependency)) queue.push(dependency);
    }
  }
  return [...reachable].sort();
}

function buildProductionCatalog(options = {}) {
  const projectRoot = options.projectRoot || repositoryInventory.projectRoot;
  const inventory = options.inventory || repositoryInventory;
  const rows = (options.repositoryPaths || inventory.listRepositoryPaths()).map(entry => {
    const normalized = normalizeRelativePath(entry.path);
    if (!normalized) return null;
    const category = inventory.categoryFor(normalized);
    const moduleName = inventory.moduleFor(normalized);
    return { ...entry, path: normalized, category, module: moduleName };
  }).filter(Boolean);
  const files = rows.filter(entry =>
    ['frontend', 'backend', 'mqtt-broker'].includes(entry.module) &&
    !entry.path.includes('/roadmap/') &&
    !SKIPPED_CATEGORIES.has(entry.category) &&
    !/(?:^|\/)[^/]*_test\.go$/.test(entry.path) &&
    SOURCE_EXTENSIONS.has(path.posix.extname(entry.path)) &&
    fs.existsSync(path.join(projectRoot, entry.path))
  );
  const paths = new Set(files.map(entry => entry.path));
  const reachable = new Set([
    ...collectFrontendReachableFiles(paths, options),
    ...collectBackendReachableFiles(paths, options)
  ]);
  return {
    cataloged: files.map(entry => entry.path).sort(),
    reachable: [...reachable].sort()
  };
}

function lineFingerprint(ruleId, relativePath, sourceLine) {
  return crypto.createHash('sha256')
    .update(`${ruleId}\0${relativePath}\0${sourceLine.trim()}`)
    .digest('hex');
}

function isGeneratedExempt(relativePath, source) {
  return GENERATED_FAMILIES.some(pattern => pattern.test(relativePath)) && GENERATED_MARKER.test(source.slice(0, 2048));
}

function finding(ruleId, relativePath, line, excerpt) {
  return {
    ruleId,
    path: relativePath,
    line,
    excerpt: excerpt.trim().slice(0, 240),
    fingerprint: lineFingerprint(ruleId, relativePath, excerpt),
    reachability: 'production-import-graph'
  };
}

function goFunctionRanges(lines) {
  const ranges = [];
  for (let index = 0; index < lines.length; index += 1) {
    const match = lines[index].match(/^func\s+(?:\([^)]*\)\s*)?([A-Za-z_]\w*)\s*\([^)]*\)[^{]*\{\s*$/);
    if (!match) continue;
    let depth = 0;
    let end = index;
    for (; end < lines.length; end += 1) {
      depth += (lines[end].match(/\{/g) || []).length;
      depth -= (lines[end].match(/\}/g) || []).length;
      if (depth === 0) break;
    }
    ranges.push({ name: match[1], start: index, end, lines: lines.slice(index, end + 1) });
    index = end;
  }
  return ranges;
}

function findPlaceholderFindings(relativePath, source) {
  const lines = String(source).split(/\r?\n/);
  const findings = [];
  lines.forEach((sourceLine, index) => {
    const code = sourceLine.replace(/\/\/.*$/, '').trim();
    if (!code) return;
    if (PLACEHOLDER_TEXT.test(code) && /(?:return|panic|throw|error|status|message|response)/i.test(code)) {
      findings.push(finding('explicit-placeholder', relativePath, index + 1, sourceLine));
    }
    if ((TERMINAL_STATE_KEY.test(code) || TERMINAL_BOOLEAN_KEY.test(code)) && SUCCESS_CONSTRUCTOR.test(code)) {
      findings.push(finding('fabricated-terminal-success', relativePath, index + 1, sourceLine));
    }
    if (/\b_\s*=\s*[^=].*\b(?:Publish|Send|Save|Create|Update|Delete)\s*\(/.test(code)) {
      findings.push(finding('discarded-side-effect-error', relativePath, index + 1, sourceLine));
    }
  });

  if (path.posix.extname(relativePath) === '.go') {
    for (const fn of goFunctionRanges(lines)) {
      if (!MUTATION_NAME.test(fn.name)) continue;
      const body = fn.lines.slice(1, -1).join('\n').replace(/\/\/.*$/gm, '').trim();
      if (/^(?:return\s+nil|return\s+true|return\s+false|return\s+["'`]?[A-Za-z0-9_-]+["'`]?)\s*$/.test(body)) {
        findings.push(finding('empty-success-mutation', relativePath, fn.start + 1, lines[fn.start]));
      }
    }
  }
  return findings;
}

function loadAllowlist(allowlistPath = DEFAULT_ALLOWLIST, options = {}) {
  const readFile = options.readFile || (target => fs.readFileSync(target, 'utf8'));
  let value;
  try {
    value = JSON.parse(readFile(allowlistPath));
  } catch (error) {
    return { entries: [], errors: [{ reason: 'allowlist-read-failed', detail: error.message }] };
  }
  if (!value || value.version !== 1 || !Array.isArray(value.entries)) {
    return { entries: [], errors: [{ reason: 'invalid-allowlist-schema' }] };
  }
  const entries = [];
  const errors = [];
  for (const [index, entry] of value.entries.entries()) {
    const normalizedPath = normalizeRelativePath(entry && entry.path);
    const valid = entry && DEFAULT_RULES.includes(entry.ruleId) && normalizedPath &&
      /^[a-f0-9]{64}$/.test(entry.fingerprint || '') &&
      typeof entry.reason === 'string' && entry.reason.trim() &&
      typeof entry.owner === 'string' && entry.owner.trim() &&
      /^\d{4}-\d{2}-\d{2}$/.test(entry.expires || '');
    if (!valid) {
      errors.push({ reason: 'malformed-allowlist-entry', index });
      continue;
    }
    entries.push({ ...entry, path: normalizedPath });
  }
  return { entries, errors };
}

function reconcileAllowlist(findings, allowlist, now = new Date()) {
  const allowed = [];
  const violations = [];
  const used = new Set();
  const errors = [...allowlist.errors];
  for (const item of findings) {
    const index = allowlist.entries.findIndex(entry =>
      entry.ruleId === item.ruleId && entry.path === item.path && entry.fingerprint === item.fingerprint
    );
    if (index < 0) violations.push(item);
    else if (new Date(`${allowlist.entries[index].expires}T23:59:59.999Z`) < now) {
      errors.push({ reason: 'expired-allowlist-entry', path: item.path, ruleId: item.ruleId });
      violations.push(item);
    } else {
      used.add(index);
      allowed.push({ finding: item, exemption: allowlist.entries[index] });
    }
  }
  const staleAllowlist = allowlist.entries.filter((entry, index) => !used.has(index));
  return { allowed, violations, staleAllowlist, errors };
}

function auditProductionPlaceholders(options = {}) {
  const projectRoot = options.projectRoot || repositoryInventory.projectRoot;
  let catalog;
  try {
    catalog = options.catalog || buildProductionCatalog({ ...options, projectRoot });
  } catch (error) {
    return {
      kind: 'aetherlink-production-placeholder-audit',
      ok: false,
      summary: { cataloged: 0, reachable: 0, findings: 0, allowed: 0, violations: 0, staleAllowlist: 0 },
      violations: [], allowed: [], staleAllowlist: [], errors: [{ reason: 'reachability-failed', detail: error.message }]
    };
  }
  const readFile = options.readSource || (relative => fs.readFileSync(path.join(projectRoot, relative), 'utf8'));
  const findings = [];
  const errors = [];
  for (const relativePath of catalog.reachable) {
    try {
      const source = readFile(relativePath);
      if (isGeneratedExempt(relativePath, source)) continue;
      findings.push(...findPlaceholderFindings(relativePath, source));
    } catch (error) {
      errors.push({ reason: 'source-read-failed', path: relativePath, detail: error.message });
    }
  }
  const allowlist = options.allowlist || loadAllowlist(options.allowlistPath || DEFAULT_ALLOWLIST, options);
  const reconciled = reconcileAllowlist(findings, allowlist, options.now || new Date());
  errors.push(...reconciled.errors);
  const ok = errors.length === 0 && reconciled.violations.length === 0 && reconciled.staleAllowlist.length === 0;
  return {
    kind: 'aetherlink-production-placeholder-audit',
    ok,
    summary: {
      cataloged: catalog.cataloged.length,
      reachable: catalog.reachable.length,
      findings: findings.length,
      allowed: reconciled.allowed.length,
      violations: reconciled.violations.length,
      staleAllowlist: reconciled.staleAllowlist.length
    },
    violations: reconciled.violations,
    allowed: reconciled.allowed,
    staleAllowlist: reconciled.staleAllowlist,
    errors
  };
}

