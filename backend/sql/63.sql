-- ③ g 绑定：存量用户按 users.authority（新建用户由创建路径自动绑定）
INSERT INTO casbin_rule (ptype, v0, v1)
SELECT 'g', u.id, u.authority
FROM users u
WHERE u.authority IN ('SYS_ADMIN', 'TENANT_ADMIN', 'TENANT_USER')
  AND u.authority IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM casbin_rule c
    WHERE c.ptype = 'g' AND c.v0 = u.id AND c.v1 = u.authority
);
